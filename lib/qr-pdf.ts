import { jsPDF } from 'jspdf'

interface PdfOptions {
  name: string
  shortUrl: string
  destinationUrl: string
  svgDataUrl: string // base64 PNG from canvas
}

/**
 * Generate a print-ready PDF with:
 * - Page 1: Large QR code with title
 * - Page 2: Instructions and details
 */
export async function generateQrPdf(options: PdfOptions): Promise<Blob> {
  const { name, shortUrl, destinationUrl, svgDataUrl } = options

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  })

  // ============ PAGE 1: QR CODE ============
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const centerX = pageWidth / 2

  // Header
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text(name, centerX, 30, { align: 'center' })

  doc.setFontSize(12)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(120)
  doc.text('Scan with your phone camera', centerX, 40, { align: 'center' })

  // QR code (15cm x 15cm = 150mm)
  const qrSize = 150
  const qrX = (pageWidth - qrSize) / 2
  const qrY = 60

  doc.addImage(svgDataUrl, 'PNG', qrX, qrY, qrSize, qrSize)

  // Short URL below
  doc.setFontSize(11)
  doc.setTextColor(120)
  doc.text(shortUrl, centerX, qrY + qrSize + 15, { align: 'center' })

  // Footer
  doc.setFontSize(9)
  doc.setTextColor(150)
  doc.text('Generated by ScanFlow', centerX, pageHeight - 15, {
    align: 'center',
  })

  // ============ PAGE 2: INSTRUCTIONS ============
  doc.addPage()

  doc.setFontSize(20)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(0)
  doc.text('About this QR code', centerX, 30, { align: 'center' })

  doc.setFontSize(11)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(60)

  // Details section
  let y = 50

  doc.setFont('helvetica', 'bold')
  doc.text('Name:', 20, y)
  doc.setFont('helvetica', 'normal')
  doc.text(name, 60, y)

  y += 8

  doc.setFont('helvetica', 'bold')
  doc.text('Short link:', 20, y)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(37, 99, 235) // blue
  doc.text(shortUrl, 60, y)
  doc.setTextColor(60)

  y += 8

  doc.setFont('helvetica', 'bold')
  doc.text('Destination:', 20, y)
  doc.setFont('helvetica', 'normal')
  // Wrap long URLs
  const destLines = doc.splitTextToSize(destinationUrl, pageWidth - 80)
  doc.text(destLines, 60, y)

  y += 8 + (destLines.length - 1) * 5

  // Divider
  y += 5
  doc.setDrawColor(200)
  doc.line(20, y, pageWidth - 20, y)
  y += 12

  // Instructions
  doc.setFontSize(14)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(0)
  doc.text('How to use this QR code', 20, y)

  y += 10

  doc.setFontSize(11)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(60)

  const tips = [
    '1. Scan the QR code with your phone camera to test it before printing.',
    '2. Print at high resolution — this PDF is print-ready at any size.',
    '3. Keep a minimum size of 2cm × 2cm for reliable scanning.',
    '4. Ensure good contrast — avoid printing on colored backgrounds.',
    '5. To change the destination, log in to your ScanFlow dashboard.',
    '   Your printed QR codes will keep working — no reprint needed.',
  ]

  tips.forEach((tip) => {
    const lines = doc.splitTextToSize(tip, pageWidth - 40)
    doc.text(lines, 20, y)
    y += lines.length * 6 + 2
  })

  // Best practices box
  y += 8
  doc.setFillColor(240, 249, 255)
  doc.roundedRect(20, y, pageWidth - 40, 40, 3, 3, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 64, 175)
  doc.setFontSize(12)
  doc.text('Pro tip', 26, y + 8)

  doc.setFont('helvetica', 'normal')
  doc.setTextColor(60)
  doc.setFontSize(10)
  const proTip =
    'Use a custom short domain for your QR codes. Your customers will see your brand instead of a generic link. Available on the Pro plan.'
  const proLines = doc.splitTextToSize(proTip, pageWidth - 52)
  doc.text(proLines, 26, y + 16)

  return doc.output('blob')
}